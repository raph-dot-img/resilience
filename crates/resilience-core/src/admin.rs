//! Shared logic of the privileged helper `resilience-admin` (ADR 0007).
//!
//! Everything here is **pure**: it decides *what* should change and refuses
//! unsafe requests, but never touches the system. The helper binary performs
//! the few side effects (state file, `gpasswd`, audit log) after these checks.
//!
//! Persistence model: the Nix configuration declares each managed account's
//! mode (`resilience.users.<n>.mode`). A mode changed with the helper is
//! recorded as an *override* in a root-owned state file, together with the
//! declared mode at the time of the change. The override wins until the
//! administrator changes the declared mode in Nix; then the declaration is
//! newer and the override is dropped. "The most recent explicit change wins."

use crate::mode::{GROUP_ADMIN, GROUP_STABLE, Mode};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::PathBuf;

/// Root-owned helper configuration generated by `nix/modules/admin.nix`.
/// The helper reads it from this fixed path only (never from the environment).
pub const ADMIN_CONFIG_PATH: &str = "/etc/resilience/admin.toml";

/// Group granting network configuration through NetworkManager's polkit rules.
pub const GROUP_NETWORK: &str = "networkmanager";

/// The groups whose membership the helper manages. It never touches others.
pub const MANAGED_GROUPS: [&str; 3] = [GROUP_STABLE, GROUP_NETWORK, GROUP_ADMIN];

/// Groups an account in `mode` belongs to (must match nix/modules/users.nix).
pub fn groups_for(mode: Mode) -> &'static [&'static str] {
    match mode {
        Mode::UltraStable => &[],
        Mode::Stable => &[GROUP_STABLE, GROUP_NETWORK],
        Mode::Advanced => &[GROUP_STABLE, GROUP_NETWORK, GROUP_ADMIN],
    }
}

/// Accept only conventional login names: `[a-z_][a-z0-9_-]{0,31}`.
pub fn valid_user_name(name: &str) -> bool {
    let mut chars = name.chars();
    matches!(chars.next(), Some('a'..='z' | '_'))
        && name.len() <= 32
        && chars.all(|c| matches!(c, 'a'..='z' | '0'..='9' | '_' | '-'))
}

/// Parse a mode exactly as written in configuration (`ultra-stable`, ...).
pub fn parse_mode(s: &str) -> Option<Mode> {
    match s {
        "ultra-stable" => Some(Mode::UltraStable),
        "stable" => Some(Mode::Stable),
        "advanced" => Some(Mode::Advanced),
        _ => None,
    }
}

/// The configuration-file spelling of a mode.
pub fn mode_id(mode: Mode) -> &'static str {
    match mode {
        Mode::UltraStable => "ultra-stable",
        Mode::Stable => "stable",
        Mode::Advanced => "advanced",
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ManagedUser {
    /// Mode declared in the Nix configuration.
    pub declared_mode: Mode,
    #[serde(default)]
    pub description: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdminConfig {
    /// Root-owned persistent mode overrides.
    pub state_file: PathBuf,
    /// Append-only audit log of security-sensitive changes.
    pub audit_log: PathBuf,
    /// Lock file serialising helper invocations.
    pub lock_file: PathBuf,
    /// Absolute paths of the only programs the helper ever runs.
    pub gpasswd: PathBuf,
    pub loginctl: PathBuf,
    /// systemd's timedatectl: sets the system clock and the hardware clock.
    pub timedatectl: PathBuf,
    /// Nix's nix-env: switches the system profile to another generation.
    pub nix_env: PathBuf,
    /// The helper itself and pkexec, for the TUI to build the fixed argv.
    pub helper: PathBuf,
    pub pkexec: PathBuf,
    /// polkit's text authentication agent (see `launch::run_with_polkit_agent`).
    pub pkttyagent: PathBuf,
    /// A login shell listed in /etc/shells (the Resilience session), passed
    /// as $SHELL to pkexec, which refuses to run otherwise.
    pub session_shell: PathBuf,
    /// Account logged in automatically on tty1; must stay Ultra-Stable.
    #[serde(default)]
    pub autologin_user: Option<String>,
    /// The machine is configured for Ultra-Stable accounts only (user
    /// namespaces and the Nix sandbox are off, ADR 0012): no account may be
    /// raised above Ultra-Stable, and earlier overrides that did are dropped.
    #[serde(default)]
    pub ultra_stable_only: bool,
    #[serde(default)]
    pub users: BTreeMap<String, ManagedUser>,
    /// kbd's loadkeys, for `set-keymap` (ADR 0017).
    #[serde(default)]
    pub loadkeys: Option<PathBuf>,
    /// The only keymap names `set-keymap` accepts.
    #[serde(default)]
    pub keymaps: Vec<String>,
}

impl AdminConfig {
    pub fn parse(text: &str) -> Result<AdminConfig, String> {
        let cfg: AdminConfig = toml::from_str(text).map_err(|e| e.to_string())?;
        if let Some(bad) = cfg.users.keys().find(|n| !valid_user_name(n)) {
            return Err(format!("invalid user name in configuration: {bad:?}"));
        }
        for p in [
            &cfg.gpasswd,
            &cfg.loginctl,
            &cfg.timedatectl,
            &cfg.nix_env,
            &cfg.helper,
            &cfg.pkttyagent,
            &cfg.pkexec,
            &cfg.session_shell,
        ]
        .into_iter()
        .chain(cfg.loadkeys.as_ref())
        {
            if !p.is_absolute() {
                return Err(format!("program path must be absolute: {}", p.display()));
            }
        }
        Ok(cfg)
    }

    pub fn load() -> Result<AdminConfig, String> {
        let text = std::fs::read_to_string(ADMIN_CONFIG_PATH)
            .map_err(|e| format!("{ADMIN_CONFIG_PATH}: {e}"))?;
        AdminConfig::parse(&text)
    }
}

/// One persistent mode change made with the helper.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Override {
    pub mode: Mode,
    /// Declared mode when the change was made; see the module documentation.
    pub declared: Mode,
    /// UTC timestamp, RFC 3339.
    pub changed: String,
    /// Login name of the account that requested the change.
    pub by: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ModeState {
    #[serde(default)]
    pub users: BTreeMap<String, Override>,
}

impl ModeState {
    /// Parse the state file. A missing file is an empty state; a corrupt one
    /// is an error (the helper then refuses to change anything).
    pub fn parse(text: &str) -> Result<ModeState, String> {
        toml::from_str(text).map_err(|e| e.to_string())
    }

    pub fn to_toml(&self) -> String {
        let mut s = String::from(
            "# Managed by resilience-admin. Mode changes made with the helper.\n\
             # Do not edit by hand; see /etc/resilience/admin.toml and ADR 0007.\n",
        );
        s.push_str(&toml::to_string(self).unwrap_or_default());
        s
    }
}

/// Where an account's effective mode comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Source {
    Declared,
    Override,
}

/// Effective mode of a managed user: a live override, else the declaration.
pub fn effective_mode(cfg: &AdminConfig, state: &ModeState, user: &str) -> Option<(Mode, Source)> {
    let declared = cfg.users.get(user)?.declared_mode;
    Some(match state.users.get(user) {
        Some(o) if o.declared == declared => (o.mode, Source::Override),
        _ => (declared, Source::Declared),
    })
}

/// Overrides made obsolete by a newer declaration (or for removed users).
pub fn stale_overrides(cfg: &AdminConfig, state: &ModeState) -> Vec<String> {
    state
        .users
        .iter()
        .filter(|(name, o)| {
            cfg.users
                .get(name.as_str())
                .is_none_or(|u| u.declared_mode != o.declared)
                || (cfg.ultra_stable_only && o.mode != Mode::UltraStable)
        })
        .map(|(name, _)| name.clone())
        .collect()
}

/// Why a mode change was refused. Shown to the user and written to the audit log.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Refusal {
    InvalidName,
    UnknownUser(String),
    AutologinMustStayUltraStable(String),
    LastAdministrator(String),
    Unchanged(String, Mode),
    UltraStableOnly(String),
}

impl fmt::Display for Refusal {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Refusal::InvalidName => f.write_str("invalid user name"),
            Refusal::UnknownUser(u) => {
                write!(f, "'{u}' is not an account managed by Resilience")
            }
            Refusal::AutologinMustStayUltraStable(u) => write!(
                f,
                "'{u}' logs in automatically without a password and must stay Ultra-Stable"
            ),
            Refusal::LastAdministrator(u) => write!(
                f,
                "'{u}' is the last Advanced account; demoting it would leave no administrator"
            ),
            Refusal::Unchanged(u, m) => write!(f, "'{u}' is already in {m} mode"),
            Refusal::UltraStableOnly(u) => write!(
                f,
                "this computer is set up for Ultra-Stable accounts only, so '{u}' cannot get \
                 more rights; an administrator must change the system configuration"
            ),
        }
    }
}

/// A validated mode change.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Change {
    pub user: String,
    pub from: Mode,
    pub to: Mode,
}

impl Change {
    /// Losing privileges: running sessions must end so they lose them too.
    pub fn is_demotion(&self) -> bool {
        self.to < self.from
    }
}

/// Decide whether `user` may be put into `to`. Pure; all server-side checks.
pub fn plan_set_mode(
    cfg: &AdminConfig,
    state: &ModeState,
    user: &str,
    to: Mode,
) -> Result<Change, Refusal> {
    if !valid_user_name(user) {
        return Err(Refusal::InvalidName);
    }
    let (from, _) =
        effective_mode(cfg, state, user).ok_or_else(|| Refusal::UnknownUser(user.into()))?;
    if from == to {
        return Err(Refusal::Unchanged(user.into(), to));
    }
    if to != Mode::UltraStable && cfg.ultra_stable_only {
        return Err(Refusal::UltraStableOnly(user.into()));
    }
    if to != Mode::UltraStable && cfg.autologin_user.as_deref() == Some(user) {
        return Err(Refusal::AutologinMustStayUltraStable(user.into()));
    }
    if from == Mode::Advanced {
        let other_admins = cfg
            .users
            .keys()
            .filter(|n| n.as_str() != user)
            .filter(|n| matches!(effective_mode(cfg, state, n), Some((Mode::Advanced, _))))
            .count();
        if other_admins == 0 {
            return Err(Refusal::LastAdministrator(user.into()));
        }
    }
    Ok(Change {
        user: user.into(),
        from,
        to,
    })
}

/// Record `change` in the state. Going back to the declared mode removes
/// the override instead of storing a redundant one.
pub fn record(state: &mut ModeState, cfg: &AdminConfig, change: &Change, by: &str, now: &str) {
    let Some(declared) = cfg.users.get(&change.user).map(|u| u.declared_mode) else {
        return;
    };
    if change.to == declared {
        state.users.remove(&change.user);
    } else {
        state.users.insert(
            change.user.clone(),
            Override {
                mode: change.to,
                declared,
                changed: now.into(),
                by: by.into(),
            },
        );
    }
}

/// Members of `group` according to an `/etc/group`-style file.
pub fn group_members(group_file: &str, group: &str) -> BTreeSet<String> {
    group_file
        .lines()
        .find_map(|line| {
            let f: Vec<&str> = line.split(':').collect();
            (f.len() == 4 && f[0] == group).then(|| {
                f[3].split(',')
                    .filter(|m| !m.is_empty())
                    .map(str::to_string)
                    .collect()
            })
        })
        .unwrap_or_default()
}

/// The actual mode of `user` according to the group file.
pub fn actual_mode(group_file: &str, user: &str) -> Mode {
    Mode::from_groups(
        MANAGED_GROUPS
            .iter()
            .filter(|g| group_members(group_file, g).contains(user)),
    )
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GroupOp {
    Add { user: String, group: &'static str },
    Remove { user: String, group: &'static str },
}

impl GroupOp {
    /// `gpasswd` arguments for this operation (fixed shape, validated name).
    pub fn gpasswd_args(&self) -> [&str; 3] {
        match self {
            GroupOp::Add { user, group } => ["-a", user, group],
            GroupOp::Remove { user, group } => ["-d", user, group],
        }
    }
}

/// Membership changes needed so that `user` has exactly the groups of `mode`
/// among [`MANAGED_GROUPS`]. Other groups are never touched.
pub fn group_ops(group_file: &str, user: &str, mode: Mode) -> Vec<GroupOp> {
    let wanted = groups_for(mode);
    MANAGED_GROUPS
        .iter()
        .filter_map(|&group| {
            let is_member = group_members(group_file, group).contains(user);
            let want = wanted.contains(&group);
            match (is_member, want) {
                (false, true) => Some(GroupOp::Add {
                    user: user.into(),
                    group,
                }),
                (true, false) => Some(GroupOp::Remove {
                    user: user.into(),
                    group,
                }),
                _ => None,
            }
        })
        .collect()
}

/// One managed account as shown by the TUI and `resilience-admin list`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AccountRow {
    pub name: String,
    pub description: String,
    pub declared: Mode,
    pub effective: Mode,
    pub source: Source,
    /// Mode according to the current group database.
    pub active: Mode,
    pub autologin: bool,
}

pub fn overview(cfg: &AdminConfig, state: &ModeState, group_file: &str) -> Vec<AccountRow> {
    cfg.users
        .iter()
        .map(|(name, u)| {
            let (effective, source) =
                effective_mode(cfg, state, name).unwrap_or((u.declared_mode, Source::Declared));
            AccountRow {
                name: name.clone(),
                description: u.description.clone(),
                declared: u.declared_mode,
                effective,
                source,
                active: actual_mode(group_file, name),
                autologin: cfg.autologin_user.as_deref() == Some(name.as_str()),
            }
        })
        .collect()
}

/// Number of accounts that can authorise administrative actions.
pub fn administrators(rows: &[AccountRow]) -> usize {
    rows.iter()
        .filter(|r| r.effective == Mode::Advanced)
        .count()
}

/// One audit-log line (logfmt). Values come from validated names and fixed
/// identifiers; free text is quoted with `"` and `\` escaped and control
/// characters removed, so one entry is always exactly one line.
pub fn audit_line(time: &str, fields: &[(&str, &str)]) -> String {
    let mut line = format!("time={time}");
    for (k, v) in fields {
        line.push(' ');
        line.push_str(k);
        line.push('=');
        let plain = !v.is_empty()
            && v.chars()
                .all(|c| c.is_ascii_alphanumeric() || "-_.:/()@+".contains(c));
        if plain {
            line.push_str(v);
        } else {
            line.push('"');
            for c in v.chars().filter(|c| !c.is_control()) {
                if c == '"' || c == '\\' {
                    line.push('\\');
                }
                line.push(c);
            }
            line.push('"');
        }
    }
    line.push('\n');
    line
}

/// Format a Unix timestamp as UTC RFC 3339 (`2026-11-14T09:30:00Z`).
pub fn rfc3339_utc(secs: i64) -> String {
    let days = secs.div_euclid(86_400);
    let rem = secs.rem_euclid(86_400);
    // Civil-from-days (Howard Hinnant's algorithm).
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!(
        "{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}Z",
        rem / 3600,
        rem % 3600 / 60,
        rem % 60
    )
}

/// Current time as RFC 3339 UTC.
pub fn now_rfc3339() -> String {
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0);
    rfc3339_utc(secs)
}

/// Why `set-keymap` refuses a layout.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeymapRefusal {
    /// This system has no keyboard layouts configured for the helper.
    Unavailable,
    /// Not a keymap name, or not one of the system's layouts.
    NotOffered,
}

impl std::fmt::Display for KeymapRefusal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            KeymapRefusal::Unavailable => "keyboard layouts cannot be changed on this system",
            KeymapRefusal::NotOffered => "this keyboard layout is not offered on this system",
        })
    }
}

/// `set-keymap` (ADR 0017): the `loadkeys` argv for `id`, only if `id` is
/// a valid name listed in the root-owned configuration.
pub fn plan_set_keymap(cfg: &AdminConfig, id: &str) -> Result<Vec<String>, KeymapRefusal> {
    let loadkeys = cfg.loadkeys.as_ref().ok_or(KeymapRefusal::Unavailable)?;
    if !cfg.keymaps.iter().any(|k| k == id) {
        return Err(KeymapRefusal::NotOffered);
    }
    crate::keyboard::loadkeys_argv(&loadkeys.to_string_lossy(), id).ok_or(KeymapRefusal::NotOffered)
}

