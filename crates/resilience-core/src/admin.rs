    #[test]
    fn override_wins_until_declaration_changes() {
        let c = cfg(&[("bob", Mode::Stable)], None);
        let mut s = ModeState::default();
        assert_eq!(
            effective_mode(&c, &s, "bob"),
            Some((Mode::Stable, Source::Declared))
        );
        let ch = plan_set_mode(&c, &s, "bob", Mode::UltraStable).expect("allowed");
        record(&mut s, &c, &ch, "carol", "t");
        assert_eq!(
            effective_mode(&c, &s, "bob"),
            Some((Mode::UltraStable, Source::Override))
        );
        assert!(stale_overrides(&c, &s).is_empty());
        // The administrator later declares a different mode in Nix: it wins.
        let c2 = cfg(&[("bob", Mode::Advanced)], None);
        assert_eq!(
            effective_mode(&c2, &s, "bob"),
            Some((Mode::Advanced, Source::Declared))
        );
        assert_eq!(stale_overrides(&c2, &s), vec!["bob".to_string()]);
        // Removed users' overrides are stale too.
        assert_eq!(
            stale_overrides(&cfg(&[], None), &s),
            vec!["bob".to_string()]
        );
    }

