    #[test]
    fn refusals() {
        let c = cfg(
            &[
                ("demo", Mode::UltraStable),
                ("carol", Mode::Advanced),
                ("bob", Mode::Stable),
            ],
            Some("demo"),
        );
        let s = ModeState::default();
        assert_eq!(
            plan_set_mode(&c, &s, "root", Mode::Stable),
            Err(Refusal::UnknownUser("root".into()))
        );
        assert_eq!(
            plan_set_mode(&c, &s, "../etc", Mode::Stable),
            Err(Refusal::InvalidName)
        );
        assert_eq!(
            plan_set_mode(&c, &s, "demo", Mode::Stable),
            Err(Refusal::AutologinMustStayUltraStable("demo".into()))
        );
        assert_eq!(
            plan_set_mode(&c, &s, "carol", Mode::Stable),
            Err(Refusal::LastAdministrator("carol".into()))
        );
        assert_eq!(
            plan_set_mode(&c, &s, "bob", Mode::Stable),
            Err(Refusal::Unchanged("bob".into(), Mode::Stable))
        );
        // With a second administrator, carol may be demoted.
        let mut s2 = ModeState::default();
        let ch = plan_set_mode(&c, &s2, "bob", Mode::Advanced).expect("promotion allowed");
        assert!(!ch.is_demotion());
        record(&mut s2, &c, &ch, "carol", "t");
        let d = plan_set_mode(&c, &s2, "carol", Mode::UltraStable).expect("allowed now");
        assert!(d.is_demotion());
    }

    #[test]
    fn state_round_trips() {
        let c = cfg(&[("bob", Mode::Stable)], None);
        let mut s = ModeState::default();
        let ch = plan_set_mode(&c, &s, "bob", Mode::Advanced).expect("allowed");
        record(&mut s, &c, &ch, "carol", "2026-11-14T10:00:00Z");
        let text = s.to_toml();
        assert!(text.contains("mode = \"advanced\""), "{text}");
        assert_eq!(ModeState::parse(&text), Ok(s));
        assert_eq!(ModeState::parse(""), Ok(ModeState::default()));
        assert!(ModeState::parse("[users.bob]\nmode = \"root\"\n").is_err());
    }

    const GROUPS: &str = "root:x:0:\nwheel:x:1:carol\nnetworkmanager:x:57:bob,carol\n\
                          resilience-stable:x:990:bob,carol\naudio:x:17:bob\n";

    #[test]
    fn group_membership_and_ops() {
        assert_eq!(actual_mode(GROUPS, "carol"), Mode::Advanced);
        assert_eq!(actual_mode(GROUPS, "bob"), Mode::Stable);
        assert_eq!(actual_mode(GROUPS, "alice"), Mode::UltraStable);
        assert!(group_ops(GROUPS, "bob", Mode::Stable).is_empty());
        assert_eq!(
            group_ops(GROUPS, "bob", Mode::Advanced),
            vec![GroupOp::Add {
                user: "bob".into(),
                group: "wheel"
            }]
        );
        let down = group_ops(GROUPS, "carol", Mode::UltraStable);
        assert_eq!(down.len(), 3);
        assert!(down.iter().all(|op| matches!(op, GroupOp::Remove { .. })));
        assert_eq!(down[2].gpasswd_args(), ["-d", "carol", "wheel"]);
        // Unrelated groups (audio) are never touched.
        assert!(
            !group_ops(GROUPS, "bob", Mode::UltraStable)
                .iter()
                .any(|op| op.gpasswd_args()[2] == "audio")
        );
    }

