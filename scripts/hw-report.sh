#!/usr/bin/env bash
# Hardware report for a PC that runs or will run Resilience OS (x86_64).
# Prints Markdown on stdout, to paste into the repository's docs.
#
#   bash hw-report.sh > hw-report.md
#
# Run it ON THE MACHINE, from any live Linux (for example the official NixOS
# minimal ISO: the Resilience live ISO has no shell, by design).
#
# - Read-only: it only reads /proc, /sys and the output of listing tools. It
#   writes nothing, loads no module, opens no serial port, never uses the
#   network and never calls sudo.
# - Works as an ordinary user. Run as root (e.g. `sudo bash hw-report.sh`
#   on a live system) it adds memory-slot details (dmidecode) and the kernel
#   log lines about missing firmware.
# - Privacy: the report leaves out serial numbers, UUIDs, MAC addresses,
#   asset tags, the host name and user names, so it can be committed to a
#   public repository. Read it before you commit it anyway.
# - Optional tools, used when present: lspci, lsusb, lsblk, dmidecode,
#   rfkill, iw, mmcli, systemd-detect-virt. Missing ones are reported.
set -u
export LC_ALL=C

VERSION=1

have() { command -v "$1" >/dev/null 2>&1; }
# Driver name behind a sysfs device link, or empty.
driver() { [ -e "$1/driver" ] && basename "$(readlink -f "$1/driver")"; }
# First line of a file, or "?" when it is missing or unreadable.
val() { local v; v=$(head -n1 -- "$1" 2>/dev/null) && [ -n "$v" ] && printf '%s' "$v" || printf '?'; }
# Mask MAC addresses and anything that looks like a serial or a UUID.
scrub() {
  sed -E \
    -e 's/([0-9A-Fa-f]{2}[:-]){5}[0-9A-Fa-f]{2}/xx:xx:xx:xx:xx:xx/g' \
    -e 's/[0-9A-Fa-f]{8}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{4}-[0-9A-Fa-f]{12}/<uuid>/g' \
    -e '/[Ss]erial|Asset Tag|UUID|iSerial/d'
}
section() { printf '\n## %s\n\n' "$1"; }
row() { printf '| %s | %s |\n' "$1" "$2"; }
table() { printf '| Item | Value |\n|---|---|\n'; }
code() { printf '```\n'; cat; printf '```\n'; }
missing=()
need() { have "$1" || missing+=("$1"); }
for t in lspci lsusb lsblk dmidecode rfkill iw mmcli systemd-detect-virt; do need "$t"; done

if [ "${1:-}" = "-h" ] || [ "${1:-}" = "--help" ]; then
  sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'
  exit 0
fi

root=no; [ "$(id -u)" = 0 ] && root=yes

printf '# Hardware report\n\n'
printf 'Generated by `scripts/hw-report.sh` v%s on %s (UTC), as root: %s.\n' \
  "$VERSION" "$(date -u '+%Y-%m-%d %H:%M')" "$root"
if [ "${#missing[@]}" -gt 0 ]; then
  printf 'Tools not found (their sections are shorter): %s.\n' "${missing[*]}"
fi

# --- Machine ---------------------------------------------------------------
section "Machine"
table
d=/sys/class/dmi/id
row "Vendor" "$(val $d/sys_vendor)"
row "Product" "$(val $d/product_name) ($(val $d/product_version))"
row "Board" "$(val $d/board_vendor) $(val $d/board_name)"
ct=$(val $d/chassis_type)
case "$ct" in
  8) ctn="portable" ;; 9) ctn="laptop" ;; 10) ctn="notebook" ;; 14) ctn="sub-notebook" ;;
  30) ctn="tablet" ;; 31) ctn="convertible" ;; 32) ctn="detachable" ;; 3) ctn="desktop" ;; *) ctn="other" ;;
esac
row "Chassis type" "$ct ($ctn)"
virt="none detected"
if have systemd-detect-virt; then
  v=$(systemd-detect-virt 2>/dev/null) && virt="$v"
elif grep -qw hypervisor /proc/cpuinfo; then
  virt="yes (hypervisor flag)"
fi
row "Virtual machine" "$virt"
if [ -r /etc/os-release ]; then
  row "Running system" "$(. /etc/os-release && printf '%s' "${PRETTY_NAME:-?}"), kernel $(uname -r)"
fi

# --- Firmware --------------------------------------------------------------
section "Boot firmware"
table
if [ -d /sys/firmware/efi ]; then
  row "Booted in" "UEFI mode"
  bits=$(val /sys/firmware/efi/fw_platform_size)
  row "UEFI firmware bitness" "$bits-bit$([ "$bits" = 32 ] && printf ' (32-bit UEFI: the Resilience ISO is untested there; try legacy/CSM)')"
  sb="?"
  f=$(ls /sys/firmware/efi/efivars/SecureBoot-* 2>/dev/null | head -n1)
  if [ -n "$f" ] && [ -r "$f" ]; then
    b=$(od -An -t u1 -j4 -N1 "$f" 2>/dev/null | tr -d ' ')
    case "$b" in 1) sb="enabled (must be disabled for the Resilience ISO)" ;; 0) sb="disabled" ;; esac
  fi
  row "Secure Boot" "$sb"
else
  row "Booted in" "legacy BIOS mode (or CSM). Whether the firmware also offers UEFI: check its setup screen"
fi
row "Firmware" "$(val $d/bios_vendor) $(val $d/bios_version), dated $(val $d/bios_date)"

# --- CPU -------------------------------------------------------------------
section "CPU"
table
model=$(grep -m1 '^model name' /proc/cpuinfo | cut -d: -f2- | sed 's/^ *//')
row "Model" "${model:-?}"
row "Architecture" "$(uname -m)"
row "Logical CPUs" "$(grep -c '^processor' /proc/cpuinfo)"
cores=$(grep -m1 '^cpu cores' /proc/cpuinfo | cut -d: -f2 | tr -d ' ')
row "Cores per package" "${cores:-?}"
flags=" $(grep -m1 '^flags' /proc/cpuinfo | cut -d: -f2-) "
hasall() { local f; for f in "$@"; do case "$flags" in *" $f "*) ;; *) return 1 ;; esac; done; }
row "64-bit (lm)" "$(hasall lm && echo yes || echo 'NO: cannot run x86_64 Resilience OS')"
level=x86-64
hasall cx16 lahf_lm popcnt sse4_1 sse4_2 ssse3 && level=x86-64-v2
[ "$level" = x86-64-v2 ] && hasall avx avx2 bmi1 bmi2 f16c fma abm movbe xsave && level=x86-64-v3
row "Instruction set level" "$level (nixpkgs needs only x86-64)"
ext=""
for f in aes avx avx2 nx vmx svm; do hasall $f && ext="$ext $f"; done
row "Notable extensions" "${ext# }"
mhz=$(val /sys/devices/system/cpu/cpu0/cpufreq/cpuinfo_max_freq)
[ "$mhz" != "?" ] && row "Max frequency" "$((mhz / 1000)) MHz"
row "Frequency driver / governor" "$(val /sys/devices/system/cpu/cpu0/cpufreq/scaling_driver) / $(val /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor)"

# --- Memory ----------------------------------------------------------------
section "Memory"
table
mt=$(awk '/^MemTotal:/ {print $2}' /proc/meminfo)
row "Usable RAM" "$((mt / 1024)) MiB"
sw=$(awk '/^SwapTotal:/ {print $2}' /proc/meminfo)
row "Swap (on this live system)" "$((sw / 1024)) MiB"
if [ "$root" = yes ] && have dmidecode; then
  printf '\nMemory array and slots (dmidecode):\n\n'
  { dmidecode -t 16 2>/dev/null | grep -E 'Maximum Capacity|Number Of Devices'
    dmidecode -t 17 2>/dev/null | grep -E '^\s*(Size|Form Factor|Locator|Type|Speed|Configured Memory Speed):'
  } | scrub | sed 's/^\s*//' | code
else
  printf '\nSlots, maximum capacity and type: run as root with dmidecode.\n'
fi

# --- Storage ---------------------------------------------------------------
section "Storage"
if have lsblk; then
  lsblk -d -e 7,11 -o NAME,TYPE,SIZE,ROTA,TRAN,RM,MODEL 2>/dev/null | code
  printf '\nROTA 1 = spinning disk, RM 1 = removable. The live stick is in this list.\n'
else
  for b in /sys/block/*; do
    n=${b##*/}; case "$n" in loop*|ram*|sr*|zram*) continue ;; esac
    printf -- '- %s: %s sectors, rotational %s, model %s\n' "$n" "$(val "$b/size")" "$(val "$b/queue/rotational")" "$(val "$b/device/model")"
  done
fi

# --- Display ---------------------------------------------------------------
section "Display"
table
gpus=$(lspci -nnk 2>/dev/null | awk '/(VGA|3D|Display) .*controller/ {p=1; print; next} p && /^\t/ {print; next} {p=0}')
for c in /sys/class/drm/card*-*; do
  [ -e "$c/status" ] || continue
  st=$(val "$c/status")
  name=${c##*/}
  modes=$(awk '!seen[$0]++' "$c/modes" 2>/dev/null | head -n3 | paste -sd, -)
  desc="$st"
  [ -n "$modes" ] && desc="$desc; modes: $modes"
  if [ "$st" = connected ]; then
    # sysfs reports size 0 for edid: test readability only.
    wcm=0 hcm=0
    [ -r "$c/edid" ] && read -r wcm hcm < <(od -An -t u1 -j21 -N2 "$c/edid" 2>/dev/null)
    [ "${wcm:-0}" -gt 0 ] && desc="$desc; panel ${wcm}x${hcm} cm (~$(awk -v w="$wcm" -v h="$hcm" 'BEGIN{printf "%.1f", sqrt(w*w+h*h)/2.54}') in)"
    first=${modes%%,*}
    if [[ "$first" =~ ^([0-9]+)x([0-9]+) ]]; then
      desc="$desc; text console with ter-i16n (8x16): $((BASH_REMATCH[1] / 8))x$((BASH_REMATCH[2] / 16)) characters"
    fi
  fi
  row "$name" "$desc"
done
fb=$(val /sys/class/graphics/fb0/name)
[ "$fb" != "?" ] && row "Framebuffer" "$fb, $(val /sys/class/graphics/fb0/virtual_size) px"
for bl in /sys/class/backlight/*; do
  [ -e "$bl" ] && row "Backlight ${bl##*/}" "$(val "$bl/brightness") of $(val "$bl/max_brightness")"
done
if sz=$(stty size 2>/dev/null); then
  row "This terminal" "${TERM:-?}, $(printf '%s' "$sz" | awk '{print $2"x"$1}') characters (rows/cols of where the script ran)"
fi
if [ -n "$gpus" ]; then printf '\nGraphics controller (lspci):\n\n'; printf '%s\n' "$gpus" | code; fi

# --- Network and radios ----------------------------------------------------
section "Network and radios"
table
for n in /sys/class/net/*; do
  i=${n##*/}; [ "$i" = lo ] && continue
  kind=wired
  [ -d "$n/wireless" ] || [ -e "$n/phy80211" ] && kind=Wi-Fi
  grep -q '^DEVTYPE=wwan' "$n/uevent" 2>/dev/null && kind="mobile broadband (WWAN)"
  [ -e "$n/device" ] || kind="$kind (virtual)"
  drv=$(driver "$n/device")
  [ -z "$drv" ] && drv=$(driver "$n/device/device")
  row "$i" "$kind, driver ${drv:-none}, state $(val "$n/operstate")"
done
for h in /sys/class/bluetooth/hci*; do
  [ -e "$h" ] || continue
  drv=$(driver "$h/device")
  row "Bluetooth ${h##*/}" "driver ${drv:-?}"
done
[ -e /sys/class/bluetooth ] && ls /sys/class/bluetooth/hci* >/dev/null 2>&1 || row "Bluetooth" "no adapter seen by the kernel"
for r in /sys/class/rfkill/rfkill*; do
  [ -e "$r" ] || continue
  row "rfkill $(val "$r/type")" "$(val "$r/name"): soft block $(val "$r/soft"), hard block $(val "$r/hard")"
done
if have iw; then
  bands=$(iw list 2>/dev/null | grep -E '^\s+Band [0-9]+:' | sed -E 's/^\s*Band 1:/2.4 GHz/; s/^\s*Band 2:/5 GHz/; s/^\s*Band 3:/60 GHz/; s/^\s*Band 4:/6 GHz/' | paste -sd, -)
  [ -n "$bands" ] && row "Wi-Fi bands" "$bands"
fi
gnss=""
for g in /sys/class/gnss/* /dev/ttyACM* /dev/ttyUSB*; do [ -e "$g" ] && gnss="$gnss ${g}"; done
row "Possible GPS/GNSS or modem ports" "${gnss:- none}"
if have mmcli; then
  mm=$(mmcli -L 2>/dev/null | scrub | paste -sd' ' -)
  row "ModemManager" "${mm:-no modem}"
fi
nets=$(lspci -nnk 2>/dev/null | awk '/(Network|Ethernet|Wireless) controller/ {p=1; print; next} p && /^\t/ {print; next} {p=0}')
if [ -n "$nets" ]; then printf '\nNetwork controllers (lspci):\n\n'; printf '%s\n' "$nets" | code; fi

# --- Power -----------------------------------------------------------------
section "Battery and power"
table
found=no
for p in /sys/class/power_supply/*; do
  [ -e "$p" ] || continue
  t=$(val "$p/type"); n=${p##*/}
  case "$t" in
    Battery)
      found=yes
      full=$(val "$p/energy_full"); design=$(val "$p/energy_full_design"); unit=Wh
      if [ "$full" = "?" ]; then full=$(val "$p/charge_full"); design=$(val "$p/charge_full_design"); unit=Ah; fi
      health="?"
      if [[ "$full" =~ ^[0-9]+$ && "$design" =~ ^[0-9]+$ && "$design" -gt 0 ]]; then
        health="$((full * 100 / design))% of design ($(awk -v f="$full" -v d="$design" -v u="$unit" 'BEGIN{printf "%.1f of %.1f %s", f/1e6, d/1e6, u}'))"
      fi
      row "$n" "$(val "$p/manufacturer") $(val "$p/model_name"), $(val "$p/technology"), $(val "$p/status") at $(val "$p/capacity")%"
      row "$n wear" "capacity $health, cycles $(val "$p/cycle_count")"
      ;;
    Mains) row "$n (mains)" "online $(val "$p/online")" ;;
    USB) row "$n (USB-C/PD)" "online $(val "$p/online")" ;;
  esac
done
[ "$found" = no ] && row "Battery" "none detected"

# --- Input, sound, USB, other -----------------------------------------------
section "Keyboard and pointing devices"
grep '^N: Name=' /proc/bus/input/devices 2>/dev/null | sed 's/^N: Name=//; s/"//g; s/^/- /'

section "Sound"
if [ -r /proc/asound/cards ]; then code </proc/asound/cards; else printf 'No sound card seen by the kernel.\n'; fi

section "USB"
if have lspci; then
  printf 'USB controllers (xHCI = USB 3):\n\n'
  lspci -nn 2>/dev/null | grep -i 'USB controller' | code
fi
if have lsusb; then printf '\nDevices (webcam, card reader, fingerprint, WWAN, Bluetooth often appear here):\n\n'; lsusb 2>/dev/null | scrub | code; fi

section "Temperatures"
for z in /sys/class/thermal/thermal_zone*; do
  [ -e "$z/temp" ] || continue
  t=$(val "$z/temp"); [[ "$t" =~ ^-?[0-9]+$ ]] && printf -- '- %s: %s °C\n' "$(val "$z/type")" "$((t / 1000))"
done

# --- Firmware problems ------------------------------------------------------
section "Missing firmware and driver errors (kernel log)"
log=""
if dmesg >/dev/null 2>&1; then log=$(dmesg 2>/dev/null)
elif have journalctl; then log=$(journalctl -k -b --no-pager -q 2>/dev/null)
fi
if [ -z "$log" ]; then
  printf 'Kernel log not readable as this user: run as root to include it.\n'
else
  hits=$(printf '%s\n' "$log" | grep -iE 'firmware: failed|direct firmware load|firmware.*(missing|not found|error)|failed to load .*\.(bin|ucode|fw)' | scrub | tail -n 30)
  if [ -n "$hits" ]; then printf '%s\n' "$hits" | code; else printf 'No missing-firmware messages.\n'; fi
fi

# --- All PCI devices ----------------------------------------------------------
if have lspci; then
  section "All PCI devices"
  lspci -nn 2>/dev/null | code
fi

printf '\n---\nTo fill by hand (not detectable): keyboard layout printed on the keys, Fn keys and Fn-lock, ports on the case, screen condition, weight, what is broken.\n'
